def host_java_apk_policy_names():
    javac = shutil.which('javac'); java = shutil.which('java'); clang = shutil.which('clang')
    if not all((javac, java, clang)): raise RuntimeError('host JDK and Clang needed')
    jni = Path(javac).resolve().parents[1] / 'include'
    with tempfile.TemporaryDirectory(prefix='bfc62-apk-host-') as temp:
        work = Path(temp)
        subprocess.run([clang, '-shared','-fPIC','-std=c11','-Wall','-Wextra','-Werror',
                        '-I'+str(jni), '-I'+str(jni/'linux'),
                        str(ROOT/'tools/android_bfp1_bridge/bfp1_jni_bridge.c'),
                        '-ldl','-o',str(work/'libbrainfuckcc_bridge.so')],check=True,timeout=30)
        stub=ROOT/'tests/fixtures/bfp1_host_device_cases61.c'
        for i,case in enumerate(CASES):
            subprocess.run([clang,'-shared','-fPIC','-std=c11','-Wall','-Wextra','-Werror',
                            '-DCASE_ID='+str(i),str(stub),'-o',str(work/('libbfc_'+case+'.so'))],
                           check=True,timeout=30)
        classes=work/'classes';classes.mkdir()
        subprocess.run([javac,'-source','8','-target','8','-d',str(classes),
                        str(SOURCE/'Bfp1Bridge.java'),str(SOURCE/'Bfp1AndroidDeviceTest.java'),
                        str(ROOT/'tests/fixtures/java/org/brainfuckcc/Bfp1ApkHostTest.java')],
                       check=True,timeout=40,capture_output=True)
        cmd=[java,'-cp',str(classes),'org.brainfuckcc.Bfp1ApkHostTest',
             str(work/'libbrainfuckcc_bridge.so'),str(work)]
        good=subprocess.run(cmd,capture_output=True,text=True,timeout=30)
        assert good.returncode==0, good.stderr
        expected=[f'PASS APK {c}' for c in CASES]+[
            'PASS APK transport_guards','PASS APK suite 9 policy fixtures']
        assert good.stdout.splitlines()==expected,good.stdout
        # A wrong APK-named policy must fail the exact shared policy assertions.
        subprocess.run([clang,'-shared','-fPIC','-std=c11','-DCASE_ID=0',str(stub),
                        '-o',str(work/'libbfc_nested.so')],check=True,timeout=30)
        wrong=subprocess.run(cmd,capture_output=True,text=True,timeout=30)
        assert wrong.returncode != 0 and 'nested:' in wrong.stderr


def make_fake_apk(where: Path) -> Path:
    apk=where/'fake-host-inspection-only.apk'
    # The bridge here is only a structural marker. No Android execution claim.
    bridge=bytearray(64);bridge[:5]=b'\x7fELF\x02';bridge[18:20]=(183).to_bytes(2,'little')
    with zipfile.ZipFile(apk,'w') as z:
        for case in gate.CASES:
            z.write(gate.LIBS/f'libbfc_{case}.so',f'lib/arm64-v8a/libbfc_{case}.so')
        z.writestr('lib/arm64-v8a/libbrainfuckcc_bridge.so',bytes(bridge))
        z.writestr('classes.dex',b'test only')
        z.writestr('AndroidManifest.xml',b'test only')
    return apk


def package_guards():
    path=gate.PROJECT/'app/src/main/AndroidManifest.xml'
    root=ET.parse(path).getroot()
    ns='{http://schemas.android.com/apk/res/android}'
    app=root.find('application')
    assert app is not None and app.attrib.get(ns+'extractNativeLibs')=='true'
    assert app.attrib.get(ns+'allowBackup')=='false'
    act=app.find('activity')
    assert act is not None and act.attrib.get(ns+'exported')=='true'
    assert act.attrib.get(ns+'name')==gate.ACTIVITY
    with tempfile.TemporaryDirectory(prefix='bfc62-apk-zip-') as td:
        apk=make_fake_apk(Path(td))
        assert gate.inspect_apk(apk)['policies_unmodified']
        with zipfile.ZipFile(apk,'r') as z:
            old={name:z.read(name) for name in z.namelist()}
        old['lib/arm64-v8a/libbfc_nested.so']=b'corrupt'
        with zipfile.ZipFile(apk,'w') as z:
            for name,data in old.items():z.writestr(name,data)
        try:gate.inspect_apk(apk)
        except RuntimeError as exc:assert 'replaced BF-generated bytes' in str(exc)
        else:raise AssertionError('corrupted APK accepted')
        apk=make_fake_apk(Path(td))
        with zipfile.ZipFile(apk,'a') as z:
            z.writestr('lib/arm64-v8a/libbfc_nested.so',b'corrupt')
        try:gate.inspect_apk(apk)
        except RuntimeError as exc:assert 'duplicate ZIP entry' in str(exc)
        else:raise AssertionError('duplicate ZIP entry accepted')


def simulated_transport():
    with tempfile.TemporaryDirectory(prefix='bfc62-mock-adb-') as td:
        temp=Path(td)
        apk=make_fake_apk(temp)
        rawapk=apk.read_bytes()
        installed={'serial':'fake-serial','sha':rawapk,'result_mode':'good','installed':False}
        actual_build=gate.BUILD
        gate.BUILD=temp
        expected_nonce=[]
        call_count=[0]
        def fake(cmd,**kw):
            assert kw.get('check') or cmd[3:7]==['shell','run-as',gate.PACKAGE,'cat'],cmd
            if cmd==['adb','devices']:
                return subprocess.CompletedProcess(cmd,0,'List of devices attached\nfake-serial\tdevice\n','')
            assert cmd[:3]==['adb','-s','fake-serial'],cmd
            args=cmd[3:]
            if args==['shell','getprop','ro.product.cpu.abi']:
                return subprocess.CompletedProcess(cmd,0,'arm64-v8a\n','')
            if args==['shell','getprop','ro.build.version.sdk']:
                return subprocess.CompletedProcess(cmd,0,'35\n','')
            if args[:2]==['install','-r']:
                installed['installed']=True
                return subprocess.CompletedProcess(cmd,0,'Success\n','')
            if args==['shell','pm','path',gate.PACKAGE]:
                assert installed['installed']
                return subprocess.CompletedProcess(cmd,0,'package:/fake/base.apk\n','')
            if args[:2]==['pull','/fake/base.apk']:
                Path(args[2]).write_bytes(installed['sha'])
                return subprocess.CompletedProcess(cmd,0,'1 pulled','')
            if args==['shell','am','force-stop',gate.PACKAGE]:
                return subprocess.CompletedProcess(cmd,0,'','')
            if args==['shell','run-as',gate.PACKAGE,'rm','-f',gate.REPORT]:
                installed['stale_cleared']=True
                return subprocess.CompletedProcess(cmd,0,'','')
            if args[:6]==['shell','am','start','-W','-n',gate.PACKAGE+'/'+gate.ACTIVITY]:
                assert installed['stale_cleared']
                assert args[6]=='--es' and args[7]=='nonce'
                expected_nonce.append(args[8])
                assert len(args[8])==32
                return subprocess.CompletedProcess(cmd,0,'Status: ok\n','')
            if args==['shell','run-as',gate.PACKAGE,'cat',gate.REPORT]:
                call_count[0]+=1
                mode=installed['result_mode']
                if mode=='missing':return subprocess.CompletedProcess(cmd,1,'','file absent')
                nonce=expected_nonce[-1]
                lines=gate.expected_transcript(nonce)
                if mode=='stale':lines[0]='BFC62_APK_BEGIN '+'0'*32
                if mode=='partial':lines=lines[:-2]
                if mode=='fail':lines[-1]=f'BFC62_APK_FAIL {nonce} JNI'
                return subprocess.CompletedProcess(cmd,0,'\n'.join(lines)+'\n','')
            raise AssertionError(f'unexpected mock command {cmd}')
        try:
            with patch.object(gate.subprocess,'run',fake):
                record=gate.run_device(apk,'adb','fake-serial',sleep=lambda n:None)
                assert record['installed_APK_namespace_verified']
                for mode in ('stale','partial','fail','missing'):
                    installed['result_mode']=mode
                    try:gate.run_device(apk,'adb','fake-serial',poll_limit=2,sleep=lambda n:None)
                    except (AssertionError, RuntimeError):pass
                    else:raise AssertionError(f'mock {mode} incorrectly accepted')
                installed['result_mode']='good'
                installed['sha']=b'mutated installed APK'
                try:gate.run_device(apk,'adb','fake-serial',sleep=lambda n:None)
                except RuntimeError as exc:assert 'differs' in str(exc)
                else:raise AssertionError('modified installed APK accepted')
            assert call_count[0]>=4
        finally:
            gate.BUILD=actual_build
    # Fake success record existed only within the deleted temporary directory.
    assert not (actual_build/'device_result62.json').exists()


def main():
    assert len(gate.CASES)==9
    assert all((gate.LIBS/f'libbfc_{name}.so').is_file() for name in gate.CASES), 'prepare APK policies first'
    host_java_apk_policy_names()
    package_guards()
    simulated_transport()
    print('PASS APK62 local: 9 JNI C stubs, policy mutation, byte-integrity, mock transport negatives')
    print('Android APK execution NOT EXECUTED')

if __name__=='__main__':main()
