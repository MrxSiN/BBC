#!/usr/bin/env python3
"""Retained AArch64 subset regression: new BF emitter preserves old native images.

The two Linux executables were generated by Brainfuck code. This test merely
compares their bytes; it does not assemble or repair any AArch64 artifact.
"""
from pathlib import Path
import hashlib
import json
import random
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
NEW = ROOT/'build/android_pie_emitter_linux_x86_64.elf'
OLD = ROOT/'evidence/history/iteration22/android_pie_emitter_linux_x86_64.elf'
OLD_SOURCE = ROOT/'evidence/history/iteration22/android_aarch64_pie_subset.bf'
NEW_SOURCE = ROOT/'experiments/android_aarch64_pie_subset.bf'


def run(executable, source):
    proc = subprocess.run([str(executable)], input=source, capture_output=True, timeout=20, check=True)
    assert len(proc.stdout) == 4193 and proc.stdout[-1] == 0, (executable, source)
    return proc.stdout


def main():
    sys.path.insert(0, str(ROOT/'tools'))
    from source_check import check_source
    assert len(check_source(OLD_SOURCE.read_bytes())) == 14771
    assert len(check_source(NEW_SOURCE.read_bytes())) == 15441
    assert OLD.stat().st_size == 472887
    assert NEW.stat().st_size == 215 + 32*15441
    rng = random.Random(20261012)
    sources = [b'', b'+', b'-', b'.', b'+-.', b'-+.', b'..........', b'++++++++++', b'++ignore++.', b'--\xff++.']
    for _ in range(118):
        commands = bytes(rng.choice(b'+-.') for _ in range(rng.randint(0,10)))
        # Accepted comment characters must not alter the emitted native image.
        if rng.getrandbits(1):
            at = rng.randint(0,len(commands))
            commands = commands[:at]+b' commentary '+commands[at:]
        sources.append(commands)
    for source in sources:
        assert run(NEW,source)==run(OLD,source), source
    report = {
        'date': '2026-10-12',
        'classification':'EXECUTED legacy source-equivalence for unchanged three-instruction subset; not Android device execution',
        'old_source_sha256':hashlib.sha256(OLD_SOURCE.read_bytes()).hexdigest(),
        'new_source_sha256':hashlib.sha256(NEW_SOURCE.read_bytes()).hexdigest(),
        'old_native_elf_sha256':hashlib.sha256(OLD.read_bytes()).hexdigest(),
        'new_native_elf_sha256':hashlib.sha256(NEW.read_bytes()).hexdigest(),
        'identical_image_cases':len(sources),
        'legacy_commands':'+-.',
        'new_commands':'+-.><,',
        'old_instruction_count':14771,
        'new_instruction_count':13891,
        'output_artifact_bytes':4192,
        'limitations':['No Android device execution', 'Source subset limited to 10 commands',
                       'New emitter supports input and pointer movement, but no loops', 'Old and new semantics differ for pointer movement because old version rejected it'],
    }
    (ROOT/'evidence/android_aarch64_legacy_equivalence.json').write_text(json.dumps(report,indent=2)+'\n')
    print(f'PASS {len(sources)} historic subset byte-identical AArch64 emitted ELF images')


if __name__=='__main__':
    main()
