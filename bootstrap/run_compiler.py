#!/usr/bin/env python3
"""Optional file/stream adapter for a compiler implemented entirely in BF.

The shipped native BF compiler performs parsing, matching, byte emission, and
ELF construction. This program only does byte-stuffing and file transport.
"""
import hashlib
import json
import pathlib
import subprocess
import sys

from transport import encode_source, extract_artifact

ROOT = pathlib.Path(__file__).resolve().parents[1]
if len(sys.argv) != 3:
    raise SystemExit('usage: python3 bootstrap/run_compiler.py source.bf destination.elf')
source = pathlib.Path(sys.argv[1]).read_bytes()
core = ROOT / 'compiler/core.bf'
binary = ROOT / 'build/compiler_x86_64_linux.elf'
expected_sha = ROOT / 'build/COMPILER_SOURCE_SHA256.txt'
evidence = ROOT / 'evidence/selfhost.json'
if not binary.is_file() or not expected_sha.is_file() or not evidence.is_file():
    raise SystemExit('verified native compiler is missing: run tests/verify_selfhost.py')
source_sha = hashlib.sha256(core.read_bytes()).hexdigest()
artifact_sha = hashlib.sha256(binary.read_bytes()).hexdigest()
record = json.loads(evidence.read_text())
if (source_sha != expected_sha.read_text().strip()
        or source_sha != record.get('source_sha256')
        or artifact_sha != record.get('artifact_elf_sha256')):
    raise SystemExit('compiler source or ELF failed bootstrap hash check: run tests/verify_selfhost.py')
run = subprocess.run([str(binary)], input=encode_source(source), capture_output=True, timeout=120)
if run.returncode:
    raise SystemExit(f'native compiler process failed with exit {run.returncode}: {run.stderr[:200]!r}')
try:
    artifact = extract_artifact(run.stdout)
except ValueError as exc:
    raise SystemExit(str(exc)) from exc
out = pathlib.Path(sys.argv[2]); out.write_bytes(artifact); out.chmod(0o700)
print(f'ELF generated by native Brainfuck compiler: {out} ({len(artifact)} bytes)')
