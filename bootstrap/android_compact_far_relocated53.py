#!/usr/bin/env python3
"""BF-owned signed-64-bit AArch64 PC-relative loop relocation.

Native words, native positions, span subtraction, branch literal values and
literal positions are generated by compiled standard Brainfuck programs. This
host only frames records and writes opaque 8-byte values at opaque word indices.
No Python machine-code/branch displacement arithmetic participates.
"""
from __future__ import annotations
import argparse,hashlib,json,os,shutil,subprocess,tempfile,zipfile
from pathlib import Path
try:
 from .android_compact_reloc_stream import make_bundle
 from .android_compact_relocated_stream52 import exact,run_bf_stage,check_framed
except ImportError:
 from android_compact_reloc_stream import make_bundle
 from android_compact_relocated_stream52 import exact,run_bf_stage,check_framed
ROOT=Path(__file__).resolve().parents[1]
SLOT=ROOT/'build/android_compact_far_slots53_x86_64_linux.elf'
LEDGER=ROOT/'build/android_compact_far_ledger53_x86_64_linux.elf'
SPAN=ROOT/'build/android_compact_span64_52_x86_64_linux.elf'
POS=ROOT/'build/android_compact_far_position53_x86_64_linux.elf'
DELTA=ROOT/'build/android_compact_far_delta53_x86_64_linux.elf'
LITERAL=bytes(8)

def _mark_patch_once(occupied, word):
 # Each BF supplied native patch spans eight bytes or two four byte words.
 # Mark both words so even overlapping zero valued literals are rejected.
 # This is generic opaque file storage and does not derive any relocation.
 byte_offset, bit = divmod(word, 8)
 occupied.seek(byte_offset)
 current = occupied.read(1)
 previous = current[0] if current else 0
 first_mask = 1 << bit
 if bit != 7:
  both_mask = first_mask | (first_mask << 1)
  if previous & both_mask:
   raise ValueError('duplicate or overlapping BF native patch')
  occupied.seek(byte_offset)
  occupied.write(bytes((previous | both_mask,)))
  return
 occupied.seek(byte_offset + 1)
 next_data = occupied.read(1)
 next_previous = next_data[0] if next_data else 0
 if previous & first_mask or next_previous & 1:
  raise ValueError('duplicate or overlapping BF native patch')
 occupied.seek(byte_offset)
 occupied.write(bytes((previous | first_mask, next_previous | 1)))

def records(stage,input_file,output_file,width,count,tag):
 run_bf_stage(stage,input_file,output_file)
 output_file.seek(0,os.SEEK_END)
 if output_file.tell()!=count*(1+width)+1:
  raise ValueError(f'BF {stage.name} record count mismatch')
 output_file.seek(-1,os.SEEK_END)
 if output_file.read(1)!=b'\0':raise ValueError(f'BF {stage.name} rejected 64-bit arithmetic')
 output_file.seek(0)
 for _ in range(count):
  if exact(output_file,1)!=tag:raise ValueError('BF output record tag mismatch')
  yield exact(output_file,width)

def compile_relocated(source:Path,target:Path,*,max_native_bytes=None,max_pairs=None,
                      code_stage=SLOT,ledger_stage=LEDGER):
 target.parent.mkdir(parents=True,exist_ok=True)
 with tempfile.TemporaryDirectory(prefix='.bf53-far-',dir=target.parent) as folder:
  d=Path(folder);bundle=d/'unrelocated.zip';code=d/'code.bin';pairs=d/'pairs.bin'
  info=make_bundle(source,bundle,max_native_bytes=max_native_bytes,max_pairs=max_pairs,
                   code_stage=code_stage,ledger_stage=ledger_stage)
  with zipfile.ZipFile(bundle) as z:
   with z.open('code.bin') as a,code.open('wb') as b:shutil.copyfileobj(a,b)
   with z.open('pairs.bin') as a,pairs.open('wb') as b:shutil.copyfileobj(a,b)
  count=info['matched_pairs']
  with tempfile.TemporaryFile('w+b') as wire_span, tempfile.TemporaryFile('w+b') as span:
   with pairs.open('rb') as f:
    for _ in range(count):
     if exact(f,1)!=b']':raise ValueError('invalid bracket-pair tag')
     wire_span.write(b'\1'+exact(f,16))
    if f.read(1):raise ValueError('trailing bracket-pair bytes')
   wire_span.write(b'\0')
   run_bf_stage(SPAN,wire_span,span)
   with tempfile.TemporaryFile('w+b') as wpos,tempfile.TemporaryFile('w+b') as wdelta:
    for span_data in check_framed(span,24):
     opening,closing,difference=span_data[:8],span_data[8:16],span_data[16:]
     wpos.write(b'\1'+opening+b'\1'+closing)
     wdelta.write(b'\1\0'+difference+b'\1\1'+difference)
    wpos.write(b'\0');wdelta.write(b'\0')
    with tempfile.TemporaryFile('w+b') as outpos,tempfile.TemporaryFile('w+b') as outdelta:
     log=d/'relocations.bin';n=0
     with code.open('r+b') as image,log.open('wb') as reloc, tempfile.TemporaryFile('w+b') as occupied:
      # BF emits word indices and relative offsets in matched-pair order.
      pseq=records(POS,wpos,outpos,8,count*2,b'P')
      dseq=records(DELTA,wdelta,outdelta,8,count*2,b'D')
      for position_word,delta_word in zip(pseq,dseq,strict=True):
       word=int.from_bytes(position_word,'little')
       if word>image.seek(0,os.SEEK_END)//4-2:
        raise ValueError('BF patch index outside native code')
       _mark_patch_once(occupied,word)
       image.seek(word*4)
       if exact(image,8)!=LITERAL:raise ValueError('branch literal placeholder mismatch')
       image.seek(word*4);image.write(delta_word)
       reloc.write(b'P'+position_word+delta_word);n+=1
      image.flush();os.fsync(image.fileno())
    if n!=2*count:raise ValueError('missing signed-64 branch literals')
  def digest(p):
   with p.open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()
  meta={'iteration':53,'format':'BF_AARCH64_PC_RELATIVE_SIGNED64_COMPACT_RELOCATED_RAW_V1',
   'artifact_kind':'RELOCATED_RAW_NATIVE_CODE_NOT_ELF',
   'source_sha256':info['raw_source_sha256'],'source_bytes':info['raw_source_bytes'],
   'native_instruction_records':info['native_instruction_records'],
   'native_code_bytes':info['native_code_bytes'],'native_word_count':info['native_word_count'],
   'bracket_pairs':count,'maximum_nesting_depth':info['maximum_observed_depth'],
   'patches_applied':n,'code_sha256':digest(code),'relocations_sha256':digest(log),
   'bracket_jump_style':'AARCH64_ADR_LDR_LITERAL_ADD_SHIFTED_BR_SIGNED64_WORDS',
   'native_patch_positions':'STANDARD_BRAINFUCK_64_BIT',
   'signed_jump_deltas':'STANDARD_BRAINFUCK_64_BIT',
   'bracket_pairing':'STANDARD_BRAINFUCK_FILE_BACKED_STACK',
   'host_role':'GENERIC_INDEXED_EIGHT_BYTE_STORAGE_AND_WIRE_FRAMES',
   'host_duplicate_patch_tracking':'SPARSE_FILE_BACKED_ONE_BIT_PER_NATIVE_WORD',
   'direct_branch_reach_limit':False,'no_fixed_command_count':True,
   'android_loader_executed':False,'original_android_policies_compiled':False}
  (d/'manifest.json').write_text(json.dumps(meta,indent=2)+'\n')
  dest=d/'result.zip'
  with zipfile.ZipFile(dest,'w',compression=zipfile.ZIP_STORED) as z:
   for item in (code,pairs,log,d/'manifest.json'):z.write(item,item.name)
  dest.replace(target)
  return meta

def main():
 a=argparse.ArgumentParser(description='BF-owned AArch64 long-range PC-relative branch relocation')
 a.add_argument('source',type=Path);a.add_argument('-o','--output',required=True,type=Path)
 a.add_argument('--max-native-bytes',type=int);a.add_argument('--max-pairs',type=int)
 x=a.parse_args();print(json.dumps(compile_relocated(x.source,x.output,max_native_bytes=x.max_native_bytes,max_pairs=x.max_pairs),indent=2))
if __name__=='__main__':main()
