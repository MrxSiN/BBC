#!/usr/bin/env python3
"""Prepare and verify an installed Android APK that loads BF-generated policies.

No Python, Gradle, Java, or C code here performs Brainfuck compilation.
The existing native Brainfuck compiler stages generate policy DSOs. This
module packages and tests them. Without --device it proves no Android run.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import shutil
import subprocess
import tempfile
import time
import zipfile

from tools.android_bfp1_bridge.device_acceptance60 import (
    BUILD as POLICY_BUILD, PROGRAMS, prepare as prepare_policies,
)

ROOT = Path(__file__).resolve().parents[2]
PROJECT = ROOT / 'tools/android_bfp1_bridge/apk62'
LIBS = PROJECT / 'app/src/main/jniLibs/arm64-v8a'
BUILD = ROOT / 'build/iteration62_android_apk'
PACKAGE = 'org.brainfuckcc.callableacceptance'
ACTIVITY = 'org.brainfuckcc.Bfp1ApkAcceptanceActivity'
REPORT = 'files/bfc62_result.txt'
CASES = tuple(PROGRAMS)


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def prepare() -> dict:
    """Call existing BF production stages, validate simulation, stage exact DSOs."""
    previous = prepare_policies()
    LIBS.mkdir(parents=True, exist_ok=True)
    records = {}
    for name in CASES:
        source = POLICY_BUILD / (name + '.so')
        dest = LIBS / ('libbfc_' + name + '.so')
        data = source.read_bytes()
        if not data.startswith(b'\x7fELF') or data[4] != 2 or int.from_bytes(data[18:20], 'little') != 183:
            raise RuntimeError(f'not an AArch64 ELF shared object: {name}')
        dest.write_bytes(data)
        if sha(dest.read_bytes()) != previous['cases'][name]['so_sha256']:
            raise RuntimeError(f'BF policy staging mismatch for {name}')
        records[name] = {'sha256': sha(data), 'bytes': len(data), 'source': str(source.relative_to(ROOT))}
    BUILD.mkdir(parents=True, exist_ok=True)
    record = {'iteration': 62, 'evidence_class': 'PREPARED_STRUCTURAL_AND_SIMULATED',
              'BF_generated_policies': records, 'simulator_cases': len(CASES),
              'apk_executed_on_android': False, 'android_compiler_selfhost': False}
    (BUILD / 'preparation.json').write_text(json.dumps(record, indent=2, sort_keys=True) + '\n')
    return record


def inspect_apk(apk: Path) -> dict:
    """Validate policy content in APK, not just the Gradle exit status."""
    if not apk.is_file():
        raise RuntimeError(f'APK not found: {apk}')
    with zipfile.ZipFile(apk) as z:
        entry_names = z.namelist()
        if len(entry_names) != len(set(entry_names)):
            raise RuntimeError("APK has duplicate ZIP entry names")
        names = set(entry_names)
        needed = {f'lib/arm64-v8a/libbfc_{case}.so' for case in CASES}
        needed.add('lib/arm64-v8a/libbrainfuckcc_bridge.so')
        needed.update(('classes.dex', 'AndroidManifest.xml'))
        missing = needed - names
        if missing:
            raise RuntimeError(f'APK missing required entries: {sorted(missing)}')
        for case in CASES:
            expected = (LIBS / f'libbfc_{case}.so').read_bytes()
            actual = z.read(f'lib/arm64-v8a/libbfc_{case}.so')
            if expected != actual:
                raise RuntimeError(f'APK replaced BF-generated bytes: {case}')
        bridge = z.read('lib/arm64-v8a/libbrainfuckcc_bridge.so')
        if not bridge.startswith(b'\x7fELF') or bridge[4] != 2 or int.from_bytes(bridge[18:20], 'little') != 183:
            raise RuntimeError('APK JNI bridge is not a 64-bit AArch64 ELF')
    return {'apk_sha256': sha(apk.read_bytes()), 'policy_count': len(CASES),
            'policies_unmodified': True, 'jni_bridge_aarch64': True}


def build_apk(gradle: str = 'gradle') -> tuple[Path, dict]:
    exe = shutil.which(gradle)
    if not exe and not Path(gradle).is_file():
        raise RuntimeError('Gradle missing; install Android SDK/NDK and Gradle, or supply a prebuilt APK')
    subprocess.run([gradle, '--no-daemon', ':app:assembleDebug'], cwd=PROJECT, check=True, timeout=900)
    apk = PROJECT / 'app/build/outputs/apk/debug/app-debug.apk'
    return apk, inspect_apk(apk)


def expected_transcript(nonce: str) -> list[str]:
    return ([f'BFC62_APK_BEGIN {nonce}'] +
            [f'PASS APK {case}' for case in CASES] +
            ['PASS APK transport_guards', 'PASS APK suite 9 policy fixtures',
             f'BFC62_APK_END {nonce}'])


def verify_transcript(content: str, nonce: str) -> list[str]:
    lines = content.splitlines()
    if lines != expected_transcript(nonce):
        raise AssertionError('installed APK JNI result incomplete, failed, repeated, or out of order')
    return lines


def run_device(apk: Path, adb: str = 'adb', serial: str | None = None,
               poll_limit: int = 25, sleep=time.sleep) -> dict:
    """Accept only a device-installed app and its freshly generated private report."""
    archive = inspect_apk(apk)
    cmd = [adb] + (['-s', serial] if serial else [])

    def invoke(*args, timeout=90):
        return subprocess.run(cmd + list(args), check=True, capture_output=True,
                              text=True, timeout=timeout)

    available = subprocess.run([adb, 'devices'], check=True, capture_output=True,
                               text=True, timeout=20).stdout
    online = [line.split('\t')[0] for line in available.splitlines()[1:]
              if line.endswith('\tdevice')]
    if serial:
        if serial not in online:
            raise RuntimeError(f'ADB device not authorized: {serial}')
    elif len(online) != 1:
        raise RuntimeError('one authorized ADB device is required, otherwise specify --serial')
    serial = serial or online[0]
    # Bind every subsequent call to the checked serial.
    cmd = [adb, '-s', serial]
    abi = invoke('shell', 'getprop', 'ro.product.cpu.abi').stdout.strip()
    sdk = invoke('shell', 'getprop', 'ro.build.version.sdk').stdout.strip()
    if abi != 'arm64-v8a' or not sdk.isdecimal() or int(sdk) < 28:
        raise RuntimeError(f'unsupported Android ABI or SDK: {abi} / {sdk}')
    invoke('install', '-r', str(apk), timeout=150)
    locations = invoke('shell', 'pm', 'path', PACKAGE).stdout.strip().splitlines()
    if len(locations) != 1 or not locations[0].startswith('package:/'):
        raise RuntimeError(f'cannot locate one installed base APK: {locations}')
    remote_apk = locations[0][len('package:'):]
    # Verify the APK installed on-device matches the exact inspected APK.
    with tempfile.TemporaryDirectory(prefix='bfc62-pull-') as td:
        received = Path(td) / 'installed.apk'
        invoke('pull', remote_apk, str(received), timeout=120)
        if sha(received.read_bytes()) != archive['apk_sha256']:
            raise RuntimeError('device-installed APK differs from locally inspected APK')

    nonce = secrets.token_hex(16)
    invoke('shell', 'am', 'force-stop', PACKAGE)
    # Delete the previous report before dispatch to reject stale success evidence.
    invoke('shell', 'run-as', PACKAGE, 'rm', '-f', REPORT)
    invoke('shell', 'am', 'start', '-W', '-n', f'{PACKAGE}/{ACTIVITY}',
           '--es', 'nonce', nonce, timeout=120)
    result = None
    for _ in range(poll_limit):
        probe = subprocess.run(cmd + ['shell', 'run-as', PACKAGE, 'cat', REPORT],
                               capture_output=True, text=True, timeout=15)
        if probe.returncode == 0:
            result = probe.stdout
            break
        sleep(1)
    if result is None:
        raise RuntimeError('installed APK did not write a readable fresh acceptance report')
    lines = verify_transcript(result, nonce)
    record = {'iteration': 62, 'classification': 'EXECUTED_INSTALLED_ANDROID_APK_JNI',
              'BF_generated_policy_device_executed': True,
              'installed_APK_namespace_verified': True,
              'android_native_compiler_selfhost': False, 'device_serial': serial,
              'device_abi': abi, 'device_sdk': int(sdk),
              'apk_sha256': archive['apk_sha256'],
              'policy_sha256': {name: sha((LIBS / f'libbfc_{name}.so').read_bytes()) for name in CASES},
              'transcript': lines}
    BUILD.mkdir(parents=True, exist_ok=True)
    (BUILD / 'device_result62.json').write_text(json.dumps(record, indent=2, sort_keys=True) + '\n')
    return record


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prepare', action='store_true')
    parser.add_argument('--build', action='store_true')
    parser.add_argument('--device', action='store_true')
    parser.add_argument('--gradle', default='gradle')
    parser.add_argument('--adb', default='adb')
    parser.add_argument('--serial')
    parser.add_argument('--apk', type=Path)
    args = parser.parse_args()
    record = prepare()
    print(f'Prepared {len(record["BF_generated_policies"])} BF-generated DSOs; Android NOT EXECUTED')
    if args.build or (args.device and not args.apk):
        apk, info = build_apk(args.gradle)
        print(f'Built APK: {apk} / {info["apk_sha256"]}')
    elif args.apk:
        apk = args.apk
        info = inspect_apk(apk)
        print(f'Inspected APK: {info["apk_sha256"]}')
    else:
        return
    if args.device:
        result = run_device(apk, args.adb, args.serial)
        print(json.dumps(result, indent=2, sort_keys=True))
    else:
        print('Android installed-APK execution: NOT EXECUTED (--device required)')

if __name__ == '__main__':
    main()
