#!/usr/bin/env python3
"""Development-only authoring aid. Saved .bf program owns ALL PE bytes and x64 lowering.

The helper creates fixed PE constants and expands the standard Brainfuck
algorithm below. No Python is used in the compiled output path.
"""
from pathlib import Path
import struct
from author_windows_seed import template

ROOT = Path(__file__).resolve().parents[1]
SLOT_COUNT = 64
SLOT_LEN = 12
PROLOGUE_LEN = 17

class BF:
    def __init__(self): self.code=[]; self.ptr=0
    def op(self, s): self.code.append(s)
    def at(self, p):
        self.op(('>' * (p-self.ptr)) if p>=self.ptr else ('<' * (self.ptr-p)))
        self.ptr=p
    def add(self, p, n):
        self.at(p)
        d=n%256
        self.op('+'*d if d<=128 else '-'*(256-d))
    def clear(self, p): self.at(p); self.op('[-]')
    def set(self, p, n): self.clear(p); self.add(p,n)
    def copy(self, src, dst, tmp):
        self.clear(dst); self.clear(tmp)
        self.at(src); self.op('[');self.op('-')
        self.add(dst,1);self.add(tmp,1);self.at(src);self.op(']')
        self.at(tmp); self.op('[');self.op('-');self.add(src,1);self.at(tmp);self.op(']')
    def begin(self,p): self.at(p);self.op('[')
    def end(self,p): self.at(p);self.op(']')
    def emit(self, data):
        # Single byte accumulator, normalized to zero on entry and exit.
        self.clear(9)
        last=0
        for c in data:
            delta=(c-last)%256
            self.add(9,delta)
            self.at(9);self.op('.')
            last=c
        self.clear(9)
    def equal(self, character):
        # Preserve source byte, set cell3 to 1 if exact match.
        self.copy(0,1,2)
        self.add(1,-character)
        self.set(3,1)
        self.begin(1)
        self.clear(1);self.clear(3)
        self.end(1)
    def if_once(self,cell,fun):
        self.begin(cell);self.clear(cell);fun();self.end(cell)

NOP = bytes([0x90])*SLOT_LEN
SLOTS = {
    ord('+'): bytes.fromhex('fe03')+bytes([0x90])*10,
    ord('-'): bytes.fromhex('fe0b')+bytes([0x90])*10,
    ord('>'): bytes.fromhex('48ffc34c39eb72020f0b9090'),
    ord('<'): bytes.fromhex('48ffcb4c39e373020f0b9090'),
}

def image_template():
    image=bytearray(0x800)
    seed=template()
    image[:0x200]=seed[:0x200]
    image[0x600:]=seed[0x400:]
    nt=0x80;p=0x98;sec=0x188
    struct.pack_into('<H',image,nt+6,3)
    struct.pack_into('<III',image,p+4,0x400,0x200,0x10000)
    struct.pack_into('<I',image,p+56,0x13000)
    image[sec:sec+120]=b'\0'*120
    for i, (name,vsize,rva,raw,off,flags) in enumerate([
        (b'.text',0x400,0x1000,0x400,0x200,0x60000020),
        (b'.idata',0x70,0x2000,0x200,0x600,0xC0000040),
        (b'.tape',0x10000,0x3000,0,0,0xC0000080),
    ]):
        struct.pack_into('<8sIIIIIIHHI',image,sec+40*i,name.ljust(8,b'\0'),vsize,rva,raw,off,0,0,0,0,flags)
    # RIP-relative addresses: tape base and one-past-end.
    init=(bytes.fromhex('4c8d25')+struct.pack('<i',0x3000-(0x1000+7))+
          bytes.fromhex('4c89e3')+
          bytes.fromhex('4c8d2d')+struct.pack('<i',0x13000-(0x1000+17)))
    assert len(init)==PROLOGUE_LEN
    exit_addr=0x1000+PROLOGUE_LEN+SLOT_COUNT*SLOT_LEN
    epilogue=bytes.fromhex('4883ec2831c9ff15')+struct.pack('<i',0x2000-(exit_addr+12))+bytes.fromhex('0f0b')
    assert len(epilogue)==14
    return image, init, epilogue

def main():
    image,prologue,epilogue=image_template()
    bf=BF()
    # Full program bytes are generated by the actual BF program at runtime.
    # Source input: BF-filtered opcode bytes, EOF as zero. Trailer: status.
    bf.set(5,SLOT_COUNT)
    bf.emit(image[:0x200]+prologue)
    bf.at(0);bf.op(',');bf.begin(0)
    # Check whether any of the 64 slots remain, without destroying count.
    bf.copy(5,10,11)
    bf.set(12,1)   # overflow candidate
    bf.clear(4)    # process candidate
    def enable():
        bf.set(4,1);bf.clear(12)
    bf.if_once(10,enable)
    def process_one():
        bf.add(5,-1)
        bf.clear(7)  # recognized flag
        for char,slot in SLOTS.items():
            bf.equal(char)
            def do_slot(slot=slot):
                bf.emit(slot);bf.set(7,1)
            bf.if_once(3,do_slot)
        # Unknown command: use harmless NOP slot, but mark emitted image invalid.
        bf.set(13,1)
        def found(): bf.clear(13)
        bf.if_once(7,found)
        def invalid(): bf.emit(NOP);bf.set(6,1)
        bf.if_once(13,invalid)
    bf.if_once(4,process_one)
    def overflow(): bf.set(6,1)
    bf.if_once(12,overflow)
    bf.at(0);bf.op(',');bf.end(0)
    # Exactly 64 padded fixed-width code slots, then imported ExitProcess(0).
    bf.begin(5)
    bf.emit(NOP)
    bf.add(5,-1)
    bf.end(5)
    bf.emit(epilogue)
    # Complete the RX raw section and the .idata raw section.
    padded=0x400-(len(prologue)+SLOT_COUNT*SLOT_LEN+len(epilogue))
    assert padded>=0
    bf.emit(bytes([0x90])*padded + image[0x600:])
    bf.at(6);bf.op('.') # zero success, one unsupported or over-limit
    bf.at(0)
    program=''.join(bf.code)
    source=('# Windows x64 limited linear compiler\n'
            '# Reads standard BF filtered bytes and emits PE with status trailer\n'
            '# Arithmetic and pointer movement with deterministic bounds trap\n'
            '# Unsupported source yields nonzero status\n'+program+'\n')
    # safe comments, zero other instruction chars in comments
    out=ROOT/'experiments/windows_linear_pe_64.bf'
    out.write_text(source,encoding='ascii')
    print('source',str(out),'instructions',len(program),'template',len(image),'bytes')
    assert len(program)<=16128, 'must be compilable by existing Linux BF compiler'

if __name__=='__main__':main()
